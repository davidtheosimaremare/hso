-- Create table for Accurate Items Catalog
create table if not exists accurate_items (
  id bigint primary key generated by default as identity,
  item_no text not null unique,
  item_name text,
  unit_name text default 'Pcs',
  unit_price numeric default 0,
  stock_quantity numeric default 0,
  available_to_sell numeric default 0,
  category text,
  brand text default 'SIEMENS',
  specs jsonb default '{}'::jsonb,
  source text default 'ACCURATE',
  created_at timestamp with time zone default now(),
  updated_at timestamp with time zone default now()
);

-- Indexes for accurate_items
create index if not exists idx_accurate_items_item_no on accurate_items (item_no);
create index if not exists idx_accurate_items_category on accurate_items (category);
create index if not exists idx_accurate_items_search on accurate_items using gin(
  to_tsvector('english', coalesce(item_no, '') || ' ' || coalesce(item_name, '') || ' ' || coalesce(category, ''))
);

-- Enable RLS on accurate_items
alter table accurate_items enable row level security;

drop policy if exists "Allow read access for authenticated users on accurate_items" on accurate_items;
create policy "Allow read access for authenticated users on accurate_items" 
  on accurate_items for select using (auth.role() = 'authenticated');

drop policy if exists "Allow write access for authenticated users on accurate_items" on accurate_items;
create policy "Allow write access for authenticated users on accurate_items" 
  on accurate_items for all using (auth.role() = 'authenticated');

-- Create table for Custom Component Converter Rules (Overrides & Manual Mappings)
create table if not exists converter_custom_rules (
  id uuid primary key default gen_random_uuid(),
  source_brand text not null, -- 'SCHNEIDER' | 'ABB' | 'OTHER'
  source_model text not null,
  category text,
  target_siemens_mlfb text not null,
  target_siemens_name text,
  spec_match_notes text,
  match_confidence integer default 100,
  created_by text,
  created_at timestamp with time zone default now(),
  updated_at timestamp with time zone default now()
);

-- Index on converter_custom_rules
create index if not exists idx_converter_rules_brand on converter_custom_rules (source_brand);
create index if not exists idx_converter_rules_source_model on converter_custom_rules (source_model);

-- Enable RLS on converter_custom_rules
alter table converter_custom_rules enable row level security;

drop policy if exists "Allow read access on converter_custom_rules" on converter_custom_rules;
create policy "Allow read access on converter_custom_rules" 
  on converter_custom_rules for select using (auth.role() = 'authenticated');

drop policy if exists "Allow write access on converter_custom_rules" on converter_custom_rules;
