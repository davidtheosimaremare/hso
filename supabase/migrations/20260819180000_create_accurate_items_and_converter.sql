-- Seed accurate_items from existing accurate_purchase_order_items and accurate_delivery_order_items
insert into accurate_items (item_no, item_name, unit_name, unit_price, category, source)
select distinct on (item_code)
  item_code as item_no,
  item_name,
  coalesce(unit_name, 'Pcs') as unit_name,
  coalesce(unit_price, 0) as unit_price,
  case 
    when item_code ~* '^(5SL|5SY|5SJ|5SP|5TJ)' then 'MCB'
    when item_code ~* '^(3VA|3VJ|3VM|3VL|3VT)' then 'MCCB'
    when item_code ~* '^(3WL|3WA|3WT|3WN)' then 'ACB'
    when item_code ~* '^(3RT|3TF|3TG|3TS)' then 'CONTACTOR'
    when item_code ~* '^(3RU|3RB)' then 'TOR'
    when item_code ~* '^(3RV)' then 'MPCB'
    when item_code ~* '^(3RW)' then 'SOFT_STARTER'
    when item_code ~* '^(6SL|6SE|6AU|V20|G120)' then 'VFD'
    when item_code ~* '^(3SU|3SB|3SE)' then 'PILOT_DEVICE'
    when item_code ~* '^(6EP|6ES7148)' then 'POWER_SUPPLY'
    when item_code ~* '^(6ED1|6ES7)' then 'PLC_AUTOMATION'
    when item_code ~* '^(5SD|5TT)' then 'SPD_MODULAR'
    when item_code ~* '(ACC|SWITCH|TERMINAL|RELAY)' then 'ACCESSORIES'
    else 'OTHER'
  end as category,
  'PO_HISTORY' as source
from accurate_purchase_order_items
where item_code is not null and trim(item_code) != ''
on conflict (item_no) do update set
  item_name = coalesce(excluded.item_name, accurate_items.item_name),
  unit_price = case when excluded.unit_price > 0 then excluded.unit_price else accurate_items.unit_price end,
  category = coalesce(excluded.category, accurate_items.category),
  updated_at = now();

